import { readFile } from "node:fs/promises";
import path from "node:path";

const names = ["limits", "yaml", "markdown", "openapi", "evidence", "matcher", "renderer", "commands", "paths", "core", "index"];

export async function createBundle(root) {
  const factories = [];
  for (const name of names) {
    const source = await readFile(path.join(root, "src", `${name}.js`), "utf8");
    factories.push(`${JSON.stringify(`./${name}`)}: function(module, exports, require) {\n${source}\n}`);
  }
  const banner = "// Generated by scripts/build.mjs. Do not edit dist/index.js directly.\n";
  return `${banner}"use strict";\n(function(nativeRequire) {\n  const modules = {\n${factories.join(",\n")}\n  };\n  const cache = Object.create(null);\n  function bundledRequire(id) {\n    if (!modules[id]) return nativeRequire(id);\n    if (cache[id]) return cache[id].exports;\n    const module = { exports: {} };\n    cache[id] = module;\n    modules[id](module, module.exports, bundledRequire);\n    return module.exports;\n  }\n  bundledRequire("./index");\n})(require);\n`;
}
